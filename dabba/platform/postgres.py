"""PostgreSQL connection support for the platform and conversation stores."""

import os
import re


def database_url() -> str:
    return os.getenv("DATABASE_URL", "").strip()


class PostgresConnection:
    """Use the same positional parameters and named rows as the SQLite stores."""

    def __init__(self, url: str):
        import psycopg
        from psycopg import ClientCursor
        from psycopg.rows import dict_row

        self.connection = psycopg.connect(
            url, cursor_factory=ClientCursor, row_factory=dict_row, connect_timeout=5
        )

    def execute(self, query, params=()):
        if params:
            query = query.replace("%", "%%").replace(" IS ?", " IS NOT DISTINCT FROM ?")
            return self.connection.execute(query.replace("?", "%s"), params)
        return self.connection.execute(query)

    def executemany(self, query, rows):
        with self.connection.cursor() as cursor:
            cursor.executemany(query.replace("?", "%s"), rows)

    def begin_write(self) -> None:
        # Match SQLite's BEGIN IMMEDIATE for read-then-write operations across
        # both stores. Transaction locks work with Neon's transaction pooler.
        self.execute("SELECT pg_advisory_xact_lock(1624833651)")

    def commit(self) -> None:
        self.connection.commit()

    def rollback(self) -> None:
        self.connection.rollback()

    def close(self) -> None:
        self.connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()


def postgres_platform_schema(schema: str) -> str:
    schema = (
        schema.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
        .replace("INTEGER", "BIGINT")
        .replace("REAL", "DOUBLE PRECISION")
        .replace("BLOB", "BYTEA")
    )
    return re.sub(r"IFNULL\((\w+), ''\)", r"(COALESCE(\1, ''))", schema)


POSTGRES_CONVERSATIONS_SCHEMA = """
    CREATE TABLE IF NOT EXISTS conversations (
        id TEXT PRIMARY KEY, user_id TEXT NOT NULL, title TEXT NOT NULL,
        messages TEXT NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
        pinned INTEGER NOT NULL DEFAULT 0, custom_title INTEGER NOT NULL DEFAULT 0,
        project_id TEXT, revision BIGINT NOT NULL DEFAULT 1
    );
    CREATE INDEX IF NOT EXISTS idx_conversations_user ON conversations(user_id);
    CREATE TABLE IF NOT EXISTS conversation_deletions (
        user_id TEXT NOT NULL, id TEXT NOT NULL, PRIMARY KEY (user_id, id)
    );
    CREATE TABLE IF NOT EXISTS messages (
        conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
        position INTEGER NOT NULL, role TEXT, model TEXT, prompt_tokens BIGINT,
        completion_tokens BIGINT, timestamp BIGINT, content TEXT,
        PRIMARY KEY (conversation_id, position)
    );
    CREATE INDEX IF NOT EXISTS idx_messages_model_timestamp ON messages(model, timestamp);
    CREATE OR REPLACE FUNCTION dabba_index_messages() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
        DELETE FROM messages WHERE conversation_id = NEW.id;
        INSERT INTO messages
            (conversation_id, position, role, model, prompt_tokens, completion_tokens, timestamp, content)
        SELECT NEW.id, position - 1, value->>'role', value->>'model',
               (value #>> '{usage,promptTokens}')::bigint,
               (value #>> '{usage,completionTokens}')::bigint,
               (value->>'timestamp')::bigint, value->>'content'
        FROM json_array_elements(NEW.messages::json) WITH ORDINALITY AS message(value, position)
        WHERE json_typeof(value) = 'object';
        RETURN NEW;
    END;
    $$;
    DROP TRIGGER IF EXISTS dabba_index_messages ON conversations;
    CREATE TRIGGER dabba_index_messages AFTER INSERT OR UPDATE OF messages ON conversations
    FOR EACH ROW EXECUTE FUNCTION dabba_index_messages();
"""


def initialize_postgres_conversations(url: str) -> None:
    conn = PostgresConnection(url)
    try:
        with conn:
            conn.begin_write()
            conn.execute(POSTGRES_CONVERSATIONS_SCHEMA)
    finally:
        conn.close()
